DASHBOARD_COLUMNS = [
    "window_id", "arrival_date", "period", "is_canceled", "prediction", "lead_time", "adr",
    "stays_in_week_nights", "stays_in_weekend_nights", "total_of_special_requests", "booking_changes",
    "market_segment", "deposit_type", "hotel", "country", "customer_type",
]
EVENT_LOG_COLUMNS = ["alert_timestamp", "window_id", "risk_probability", "status", "reviewed_by",
                     "investigation_notes", "action_taken"]


def _clean(o):
    """Make nested results JSON-safe (numpy scalars, NaN, timestamps)."""
    if isinstance(o, dict):
        return {str(k): _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating, float)):
        return None if math.isnan(float(o)) or math.isinf(float(o)) else float(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if isinstance(o, (pd.Timestamp,)):
        return o.isoformat()
    return o


def _seed_event_log(path: Path, win: pd.DataFrame, reset: bool) -> None:
    """Create the investigation log, pre-filled with the first alert of each alert run (test period)."""
    if path.exists() and not reset:
        return
    test = win[win["split"] == "test"].copy()
    prev = test["alert"].shift(1, fill_value=False)
    first = test[test["alert"] & ~prev]
    log = pd.DataFrame({
        "alert_timestamp": first["window_start"].dt.strftime("%Y-%m-%d"),
        "window_id": first["window_id"],
        "risk_probability": first["risk"].round(3),
        "status": first["status"],
        "reviewed_by": "",
        "investigation_notes": "Auto-generated by the pipeline. Needs human review.",
        "action_taken": "",
    })
    log[EVENT_LOG_COLUMNS].to_csv(path, index=False)


def _score_block(name, win, idx, score, threshold, cfg, probabilistic):
    sub = win.loc[idx]
    return classification_metrics(sub["degradation_label"].to_numpy(), np.asarray(score), threshold,
                                  cfg.alert_budget, probabilistic)


def run_pipeline(cfg: Config | None = None, source: str = "auto", real_csv: Path | None = None,
                 paths: Paths | None = None, write: bool = True, reset_log: bool = False,
                 verbose: bool = True) -> dict:
    cfg = cfg or Config()
    paths = (paths or Paths.default())
    real_csv = real_csv or (paths.raw / "hotel_bookings.csv")
    log = print if verbose else (lambda *a, **k: None)
    if write:
        paths.ensure()

    # ---- 1. data understanding ---------------------------------------------
    df, source_name = load_bookings(cfg, source, real_csv)
    df = df.sort_values("arrival_date", kind="stable").reset_index(drop=True)
    origin = df["arrival_date"].min().normalize()
    df["window_id"] = ((df["arrival_date"] - origin).dt.days // cfg.window_days).astype(int)
    n_windows = int(df["window_id"].max()) + 1
    n_train_w = int(round(cfg.train_frac * n_windows))
    first_mon = n_train_w + int(round(cfg.reference_frac * n_windows))
    wid = df["window_id"].to_numpy()
    train_m = wid < n_train_w
    ref_m = (wid >= n_train_w) & (wid < first_mon)
    mon_m = wid >= first_mon
    df["period"] = np.select([train_m, ref_m], ["train", "reference"], default="monitoring")
    log(f"[1/7] {source_name} data: {len(df):,} bookings, {n_windows} windows of {cfg.window_days} days "
        f"(train {n_train_w}, reference {first_mon - n_train_w}, monitoring {n_windows - first_mon})")

    # ---- 2. baseline business model ----------------------------------------
    baseline = train_baseline(df[train_m], cfg.seed)
    proba = baseline.predict_proba(prepare_features(df))[:, 1]
    y = df[TARGET].to_numpy()
    df["prediction"] = proba

    # ---- 3. reference period -----------------------------------------------
    base_train = classification_report_dict(y[train_m], proba[train_m])
    base_ref = classification_report_dict(y[ref_m], proba[ref_m])
    f1_ref = base_ref["f1"]
    ref_window_f1 = [f1_score(y[ref_m][i], (proba[ref_m][i] >= 0.5).astype(int), zero_division=0)
                     for i in pd.Series(np.arange(ref_m.sum())).groupby(wid[ref_m]).indices.values()]
    f1_ref_std = float(np.std(ref_window_f1))
    log(f"[2/7] baseline F1: train {base_train['f1']:.3f} | reference (held out) {f1_ref:.3f} "
        f"(window-to-window sd {f1_ref_std:.3f})")
    profile = build_reference_profile(df[ref_m].reset_index(drop=True), proba[ref_m], y[ref_m], cfg,
                                      f1_ref, f1_ref_std)

    # ---- 4/5. monitoring windows and signals -------------------------------
    df_mon = df[mon_m].reset_index(drop=True)
    win = build_window_table(df_mon, proba[mon_m], y[mon_m], profile, cfg, origin)
    win = add_temporal_features(win, cfg, f1_ref)
    log(f"[3/7] monitoring table: {len(win)} windows x {win.shape[1]} columns")

    # ---- 6. target generation + leakage guard -------------------------------
    check_no_leakage(RISK_FEATURES)
    win = add_degradation_labels(win, cfg, f1_ref)
    f1_thr = f1_ref - cfg.drop_threshold
    labeled_pos = np.flatnonzero(win["degradation_label"].notna().to_numpy())
    tr, va, te = chronological_split(len(labeled_pos), cfg.split_fractions, gap=cfg.horizon)
    idx_tr, idx_va, idx_te = labeled_pos[tr], labeled_pos[va], labeled_pos[te]
    ylab = win["degradation_label"]
    for nm, ix in (("train", idx_tr), ("val", idx_va), ("test", idx_te)):
        if len(ix) == 0:
            raise ValueError(f"The {nm} segment is empty: not enough labeled windows ({len(labeled_pos)}).")
    if ylab.loc[idx_tr].nunique() < 2:
        raise ValueError("Training windows contain a single class: no degradation (or only degradation) was "
                         "observed. Change drop_threshold / horizon, or use data with drift.")
    log(f"[4/7] labels: prevalence train {ylab.loc[idx_tr].mean():.2f} | val {ylab.loc[idx_va].mean():.2f} | "
        f"test {ylab.loc[idx_te].mean():.2f}  (horizon={cfg.horizon}, drop={cfg.drop_threshold})")

    # ---- 7. risk-model training on the chronological split -------------------
    Xtr = win.loc[idx_tr, RISK_FEATURES]
    ytr = ylab.loc[idx_tr].to_numpy()
    pos_weight = float((ytr == 0).sum() / max((ytr == 1).sum(), 1))
    results, fitted, val_scores, test_scores = {}, {}, {}, {}
    for name, est in make_candidates(cfg.seed, pos_weight).items():
        est.fit(Xtr, ytr)
        fitted[name] = est
        sv = est.predict_proba(win.loc[idx_va, RISK_FEATURES])[:, 1]
        st = est.predict_proba(win.loc[idx_te, RISK_FEATURES])[:, 1]
        thr = choose_threshold(ylab.loc[idx_va], sv)
        val_scores[name], test_scores[name] = sv, st
        results[name] = {"val": _score_block(name, win, idx_va, sv, thr, cfg, True),
                         "test": _score_block(name, win, idx_te, st, thr, cfg, True), "threshold": thr,
                         "kind": "model"}
    # simple rules for honest comparison: "is drift high?" and "did F1 already fall?"
    rules = {"rule: drift score": win["drift_roll3"], "rule: F1 already dropped": -win["metric_change"]}
    for name, s in rules.items():
        sv, st = s.loc[idx_va].to_numpy(), s.loc[idx_te].to_numpy()
        thr = choose_threshold(ylab.loc[idx_va], sv)
        val_scores[name], test_scores[name] = sv, st
        results[name] = {"val": _score_block(name, win, idx_va, sv, thr, cfg, False),
                         "test": _score_block(name, win, idx_te, st, thr, cfg, False), "threshold": thr,
                         "kind": "rule"}

    model_names = [n for n, r in results.items() if r["kind"] == "model"]
    best = max(model_names, key=lambda n: (np.nan_to_num(results[n]["val"]["pr_auc"], nan=-1),
                                           np.nan_to_num(results[n]["val"]["roc_auc"], nan=-1)))
    threshold = results[best]["threshold"]
    healthy = win.loc[idx_tr][ylab.loc[idx_tr] == 0]
    ref_vals = (healthy if len(healthy) else win.loc[idx_tr])[RISK_FEATURES].median().to_dict()
    risk_model = RiskModel(best, fitted[best], list(RISK_FEATURES), threshold, ref_vals, f1_ref,
                           cfg.horizon, cfg.drop_threshold, meta={"config": cfg.to_dict(), "source": source_name})
    log(f"[5/7] selected risk model on validation PR-AUC: {best} (alert threshold {threshold:.3f})")

    # ---- score every window ----------------------------------------------------
    win["risk"] = risk_model.score(win)
    win["status"] = risk_model.status(win["risk"])
    win["alert"] = win["risk"] >= threshold
    split = pd.Series("unlabeled", index=win.index)
    split.loc[idx_tr], split.loc[idx_va], split.loc[idx_te] = "train", "val", "test"
    split.loc[(split == "unlabeled") & win["degradation_label"].notna()] = "purged"
    win["split"] = split
    contrib = risk_model.contributions(win)
    contrib.columns = [f"contrib_{c}" for c in contrib.columns]
    win_out = pd.concat([win, contrib], axis=1)

    # ---- 8. evaluation: lead time, false alerts, calibration --------------------
    test_start = int(idx_te[0])
    tail = win.loc[test_start:]
    lead = lead_time_analysis(tail, cfg.horizon, cfg.window_days)
    fa = false_alerts_per_month(win.loc[idx_te], cfg.window_days)
    cal = calibration_table(ylab.loc[idx_te].to_numpy(), win.loc[idx_te, "risk"].to_numpy())
    mean_abs = contrib.loc[idx_te].abs().mean()
    mean_abs.index = [c.replace("contrib_", "") for c in mean_abs.index]
    log(f"[6/7] test: PR-AUC {results[best]['test']['pr_auc']:.3f} | ROC-AUC {results[best]['test']['roc_auc']:.3f} | "
        f"precision {results[best]['test']['precision']:.2f} | recall {results[best]['test']['recall']:.2f} | "
        f"lead {lead['mean_lead_windows']:.1f} windows | false alerts/month {fa['false_alerts_per_month']:.1f}")

    comparison = pd.DataFrame([
        {"method": n, "kind": r["kind"], "split": sp, **{k: v for k, v in r[sp].items()}}
        for n, r in results.items() for sp in ("val", "test")
    ])
    metrics = _clean({
        "data_source": source_name,
        "synthetic_warning": ("Synthetic data validates the pipeline and the method, not real-world "
                              "predictive validity." if source_name == "synthetic" else None),
        "config": cfg.to_dict(),
        "dataset": {"n_bookings": len(df), "n_windows": n_windows, "n_train_windows": n_train_w,
                    "n_reference_windows": first_mon - n_train_w, "n_monitoring_windows": n_windows - first_mon,
                    "date_start": df["arrival_date"].min(), "date_end": df["arrival_date"].max()},
        "baseline_model": {"train": base_train, "reference_holdout": base_ref, "f1_ref": f1_ref,
                           "reference_window_f1_sd": f1_ref_std, "degradation_f1_threshold": f1_thr},
        "labels": {"n_labeled": len(labeled_pos), "prevalence": {"train": ylab.loc[idx_tr].mean(),
                   "val": ylab.loc[idx_va].mean(), "test": ylab.loc[idx_te].mean()},
                   "n_windows": {"train": len(idx_tr), "val": len(idx_va), "test": len(idx_te)}},
        "selected_model": best, "alert_threshold": threshold,
        "test_metrics_selected": results[best]["test"], "lead_time": lead, "false_alerts": fa,
        "results": results,
        "mean_abs_contribution_test": mean_abs.sort_values(ascending=False).to_dict(),
        "risk_features": RISK_FEATURES,
    })

    # ---- persist ---------------------------------------------------------------
    if write:
        joblib.dump(baseline, paths.models / "baseline_model.joblib")
        joblib.dump(profile, paths.models / "reference_profile.joblib")
        joblib.dump(risk_model, paths.models / "risk_model.joblib")
        win_out.to_csv(paths.processed / "monitoring_table.csv", index=False)
        df.loc[df["period"] != "train", [c for c in DASHBOARD_COLUMNS if c in df.columns]].to_csv(
            paths.processed / "scored_bookings.csv.gz", index=False)
        comparison.to_csv(paths.reports / "model_comparison.csv", index=False)
        (paths.reports / "metrics.json").write_text(json.dumps(metrics, indent=2))
        _seed_event_log(paths.processed / "event_log.csv", win, reset_log)
        plots.risk_vs_f1(win, f1_ref, f1_thr, threshold, paths.figures / "risk_vs_f1.png")
        plots.drift_timeline(win, paths.figures / "drift_timeline.png")
        plots.pr_curves(ylab.loc[idx_te].to_numpy(), test_scores, paths.figures / "pr_curves.png")
        plots.calibration_plot(cal, paths.figures / "calibration.png", f"Calibration on test windows ({best})")
        plots.signal_importance(mean_abs, paths.figures / "signal_importance.png")
        _write_results_md(paths.reports / "RESULTS.md", metrics, comparison)
        log(f"[7/7] artifacts written under {paths.root}")

    return {"windows": win_out, "metrics": metrics, "comparison": comparison, "risk_model": risk_model,
            "baseline": baseline, "profile": profile, "bookings": df, "calibration": cal}


def _fmt(v, d=3):
    return "n/a" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{v:.{d}f}"


def _write_results_md(path: Path, m: dict, comp: pd.DataFrame) -> None:
    t = comp[comp["split"] == "test"]
    rows = "\n".join(
        f"| {r.method} | {_fmt(r.pr_auc)} | {_fmt(r.roc_auc)} | {_fmt(r.precision, 2)} | {_fmt(r.recall, 2)} | "
        f"{_fmt(r.recall_at_budget, 2)} | {_fmt(r.brier)} |" for r in t.itertuples())
    d, b, lt, fa = m["dataset"], m["baseline_model"], m["lead_time"], m["false_alerts"]
    warn = f"\n> **{m['synthetic_warning']}**\n" if m.get("synthetic_warning") else ""
    path.write_text(f"""# Results (auto-generated by `scripts/run_pipeline.py`)
{warn}
- Data source: **{m['data_source']}**, {d['n_bookings']:,} bookings, {d['n_windows']} windows
- Baseline cancellation model F1 on the held-out reference period: **{_fmt(b['f1_ref'])}**
  (degradation = F1 below **{_fmt(b['degradation_f1_threshold'])}**)
- Target: any of the next {m['config']['horizon']} windows below the threshold
- Selected risk model: **{m['selected_model']}**, alert threshold {_fmt(m['alert_threshold'])}

## Test windows (untouched, chronologically last)

| Method | PR-AUC | ROC-AUC | Precision | Recall | Recall @ {int(m['config']['alert_budget']*100)}% alerts | Brier |
|---|---|---|---|---|---|---|
{rows}

- Degradation events in the test period: {lt['n_events']}; detected early: {lt['n_detected_early']}
  (mean lead time {_fmt(lt['mean_lead_windows'], 1)} windows = {_fmt(lt['mean_lead_days'], 1)} days)
- False alerts per month: {_fmt(fa['false_alerts_per_month'], 1)}
- Rules ("drift score", "F1 already dropped") are included so the classifier has to earn its place.
""")
